"""## Parte 5: Análisis de Outliers (Valores Atípicos)

### 5.1 Identificación y Limpieza de Outliers por Modelo (Criterio de Tukey)

El precio de los vehículos usados varía enormemente según su estado, equipamiento o urgencia del vendedor. Sin embargo, los valores atípicos extremos (publicaciones con precios excesivamente altos o bajos para su gama) sesgan drásticamente las líneas de regresión lineal simple.

Aplicamos el Criterio de Tukey utilizando el Rango Intercuartílico ( IQR=Q3−Q1 ) con un factor de escala de  1.5 . Es fundamental notar que esta limpieza se ejecuta por separado e individualmente para cada modelo, evitando así que los rangos de precios de un auto de alta gama como el Vento distorsionen la detección de outliers de un auto económico como el Gol.
"""

def limpiar_outliers_por_modelo(df, col_precio='price_usd', factor=1.5, mostrar_info=True):
  """Calcula el Criterio de Tukey (IQR) sobre el precio de cada modelo por separado,

  elimina los outliers locales y devuelve un DataFrame único reagrupado.
  """
  subconjuntos_limpios = []

  # Iteramos por cada modelo de forma 100% aislada
  for modelo, grupo in df.groupby('model'):
    q1 = grupo[col_precio].quantile(0.25)
    q3 = grupo[col_precio].quantile(0.75)
    iqr = q3 - q1

    # Bigotes de Tukey adaptados al dominio
    lim_inf = q1 - factor * iqr
    lim_sup = q3 + factor * iqr

    # Máscara booleana para filtrar el grupo actual (aquí es donde se descartan los outliers)
    mascara = (grupo[col_precio] >= lim_inf) & (grupo[col_precio] <= lim_sup)
    cumplen = mascara.sum()
    outliers = (~mascara).sum()

    if mostrar_info:
      print(f"--- Modelo: {modelo} ---")
      print(f"IQR: {iqr:.2f} | Rango aceptable: [${lim_inf:.2f} - ${lim_sup:.2f}]")
      print(f"Conservados: {cumplen} | Outliers eliminados: {outliers}\n")

    # Guardamos únicamente el segmento saneado (excluyendo outliers)
    subconjuntos_limpios.append(grupo[mascara])

  # Reagrupamos todos los modelos en un único DataFrame unificado
  df_reagrupado = pd.concat(subconjuntos_limpios, ignore_index=True)  #
  return df_reagrupado





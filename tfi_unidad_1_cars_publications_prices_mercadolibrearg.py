"""#### 7.1.2 Evaluación de Rendimiento del Modelo e Interpretación Teórica del $R^2$

Para interpretar la calidad de nuestros modelos matemáticos de forma correcta, analizamos dos métricas fundamentales:

1. **Coeficiente de Determinación ($R^2$):** Representa la proporción de la variabilidad o variación del precio que puede explicarse a través de la variable independiente (el kilometraje). **Es incorrecto definir el $R^2$ como un 'porcentaje de fiabilidad' del modelo.** Un $R^2 = 0.62$ indica que el kilometraje logra explicar el $62.53\%$ de la variación observada en los precios de los vehículos, dejando el porcentaje restante a otros factores no incluidos (como el estado estético, el año o el equipamiento). Un valor negativo de $R^2$ indica que el modelo es tan deficiente que realiza predicciones peores que la simple media aritmética de los precios.
2. **Error Absoluto Medio (MAE):** Cuantifica la magnitud promedio de los errores de predicción en términos absolutos directamente en la unidad de medida original (dólares estadounidenses USD). Nos indica, en promedio, por cuántos dólares se desvía la estimación del modelo respecto al precio de publicación real.
"""

from sklearn.metrics import mean_absolute_error, r2_score

def evaluar_modelo_regresion(modelo, particion_test, nombre_modelo):
    """
    Evalúa el rendimiento de un modelo de regresión lineal en test.
    """
    X_test = particion_test[['km']]
    y_test = particion_test['price_usd']
    y_pred = modelo.predict(X_test)

    r2 = r2_score(y_test, y_pred)
    mae = mean_absolute_error(y_test, y_pred)

    print(f"=== EVALUACIÓN: {nombre_modelo} ===")
    print(f"Coeficiente de Determinación (R²): {r2:.4f}")
    if r2 >= 0:
        print(f"Varianza explicada (Fiabilidad): {r2 * 100:.2f}%")
    else:
        print(f"Varianza explicada: N/A (Predice peor que el promedio del precio)")
    print(f"Error Absoluto Medio (MAE): ${mae:.2f} USD\n")

    return {"r2": r2, "mae": mae}

